# Safe Excel / CSV saver that bypasses pandas 3.1.0's openpyxl bug
def save_eval_checkpoint(records, xlsx_path, csv_path):
    df = pd.DataFrame(records)
    # 1. Save CSV
    df.to_csv(csv_path, index=False, encoding="utf-8-sig")

    # 2. Save XLSX safely via native openpyxl
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "GuardDengue Medichat"
    for r in dataframe_to_rows(df, index=False, header=True):
        ws.append(r)
    wb.save(xlsx_path)

# 1. Load Knowledge Base
with open(KB_FILE, "r", encoding="utf-8") as f:
    knowledge_base = json.load(f)

for doc in knowledge_base:
    for field in ("source", "evidence_level", "publication_date"):
        doc["metadata"].setdefault(field, "Not provided")
    doc.setdefault("question_intent", doc["category"])

# 2. Check if Retriever is already loaded
if "embedder" not in globals() or "corpus_embeddings" not in globals():
    print(f"Loading retriever ({DENSE_RETRIEVER_ID}) on CPU...")
    embedder = SentenceTransformer(DENSE_RETRIEVER_ID, device="cpu")
    corpus_texts = [
        f"Topic: {doc['category']} | Intent: {doc['question_intent']} | Content: {doc['content']}"
        for doc in knowledge_base
    ]
    corpus_embeddings = embedder.encode(
        corpus_texts,
        convert_to_numpy=True,
        normalize_embeddings=True,
        show_progress_bar=False
    )
else:
    print("Retriever already in memory. Skipping reload.")

def retrieve_top_evidence(query: str, top_k: int = TOP_K):
    query_embedding = embedder.encode(
        [query],
        convert_to_numpy=True,
        normalize_embeddings=True,
        show_progress_bar=False
    )[0]
    scores = corpus_embeddings @ query_embedding
    ranked_indices = scores.argsort()[::-1][: min(top_k, len(knowledge_base))]

    matches = []
    for idx in ranked_indices:
        doc = knowledge_base[int(idx)]
        matches.append({
            "score": float(scores[idx]),
            "category": doc["category"],
            "content": doc["content"],
            "metadata": doc["metadata"]
        })
    return matches

# 3. Check if Model is already in GPU VRAM
if "model" not in globals() or "tokenizer" not in globals():
    print(f"Loading {MODEL_ID} into GPU VRAM in 4-bit...")
    try:
        HF_TOKEN = userdata.get("HF_TOKEN")
    except Exception:
        HF_TOKEN = None

    tokenizer = AutoTokenizer.from_pretrained(MODEL_ID, token=HF_TOKEN)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    bnb_config = BitsAndBytesConfig(
        load_in_4bit=True,
        bnb_4bit_quant_type="nf4",
        bnb_4bit_compute_dtype=torch.float16,
        bnb_4bit_use_double_quant=True
    )

    model = AutoModelForCausalLM.from_pretrained(
        MODEL_ID,
        quantization_config=bnb_config,
        device_map="auto",
        token=HF_TOKEN
    )
    model.eval()
else:
    print("Medichat-Llama3-8B already loaded in GPU memory! Skipping reload.")

