"""
GuardDengue — LangGraph Node: Screener (Zone 2)
"""
from typing import Any
from app.schemas.state import DengueGraphState
from app.safety.screener import screen_query

def screener_node(state: DengueGraphState) -> dict[str, Any]:
    decision = screen_query(state["question"], language=state.get("language", "en"))
    
    trace_step = {
        "node": "screener_node",
        "route": decision.route,
        "matched_rules": decision.matched_rules,
        "intent": decision.intent_description,
        "dial_108": decision.dial_108,
        "latency_ms": decision.zone2_latency_ms
    }

    updates: dict[str, Any] = {
        "route": decision.route,
        "matched_rules": decision.matched_rules,
        "intent_description": decision.intent_description,
        "zone2_latency_ms": decision.zone2_latency_ms,
        "safety_disclaimer": decision.safety_disclaimer,
        "telephony_action": decision.telephony_action,
        "trace_steps": [trace_step],
    }
    
    # Store direct template if generated by Zone 2 screener
    if decision.direct_template:
        updates["draft"] = decision.direct_template
        updates["answer"] = decision.direct_template

    return updates
